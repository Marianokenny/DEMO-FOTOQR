/** Picks dark or light text for a given background color (WCAG relative luminance). */
export function readableOn(hex: string): "#15120e" | "#ffffff" {
  const n = parseInt(hex.replace("#", ""), 16);
  const ch = [(n >> 16) & 255, (n >> 8) & 255, n & 255].map((v) => {
    const c = v / 255;
    return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
  });
  const lum = 0.2126 * ch[0] + 0.7152 * ch[1] + 0.0722 * ch[2];
  return lum > 0.32 ? "#15120e" : "#ffffff";
}
